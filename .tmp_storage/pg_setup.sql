DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'postgres') THEN
    CREATE ROLE postgres LOGIN SUPERUSER PASSWORD 'PUT_YOUR_POSTGRES_PASSWORD_HERE';
  ELSE
    ALTER ROLE postgres WITH LOGIN SUPERUSER PASSWORD 'PUT_YOUR_POSTGRES_PASSWORD_HERE';
  END IF;
END $$;

SELECT 'postgres role ready';

SELECT 'CREATE DATABASE joddb OWNER postgres'
WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = 'joddb');
